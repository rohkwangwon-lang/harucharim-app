for (const n of ['반숙란', '하몽 세라노', '훈제연어']) no(has(n, '생식동물성'), `"${n}" 에 생식동물성이 붙었다 — 덜익힘과 섞이면 안 된다`)

/*
 * 훈제오리 — 2026-10-13. IARC 의 가공육 정의(염장·경화·발효·훈연)에 들고, 호중구가 낮은 분께는 "데워서" 가 붙어야 한다.
 * 훈제 닭가슴살까지 넓히지는 않았다(정해 주신 범위가 아니다).
 */
for (const n of ['훈제오리', '훈제오리고기', '유자 훈제오리 저당 포케 샐러드', '오리훈제 슬라이스', '살라미에멘탈 샌드위치']) no(!has(n, '가공육'), `"${n}" 에 가공육이 안 붙는다`)
for (const n of ['훈제 닭가슴살', '오리백숙', '오리주물럭']) no(has(n, '가공육'), `"${n}" 에 가공육이 붙었다 — 훈제오리가 아니다`)

/*
 * 날로 먹는 과일·채소 — 호중구가 낮은 분께 "씻어서 드세요" 를 붙이려는 태그. 군을 함께 보아야 해서 withAutoTags 로 본다.
 */
const produceTagged = (n: string, g: string) => withAutoTags(n, [], g).includes('생채소과일' as never)
const PRODUCE_YES: [string, string][] = [['사과_후지_생것', '과일'], ['상추_적상추_생것', '채소'], ['닭가슴살 리코타 샐러드', '가공식품'],
  ['양배추겉절이', '반찬·조림·볶음'], ['컵과일 (사과·포도)', '가공식품'], ['연어샐러드', '어패류']]
const PRODUCE_NO: [string, string][] = [['시금치_데친것', '채소'], ['감_말린것', '과일'], ['샐러드 드레싱 오리엔탈', '가공식품'],
  ['감자샐러드', '반찬·조림·볶음'], ['에그샐러드 샌드위치', '가공식품'], ['샐러드유', '유지·당류'], ['마카로니 샐러드', '반찬·조림·볶음'],
  ['겉절이김치', '반찬·조림·볶음'], ['프로틴 샐러드바 플레인', '가공식품'], ['사과주스', '음료'], ['시저 샐러드', '외식·프랜차이즈']]
for (const [n, g] of PRODUCE_YES) no(!produceTagged(n, g), `"${n}"(${g}) 에 생채소과일이 안 붙는다 — 씻는 방법이 안 뜬다`)
for (const [n, g] of PRODUCE_NO) no(produceTagged(n, g), `"${n}"(${g}) 에 생채소과일이 붙었다 — 익히거나 말린 것, 양념, 과자이거나 밖에서 사 드시는 것이다`)

/* 비타민 K — 와파린 규칙이 이름을 든 다섯 가지. 수치가 없는 자료에도 붙어야 한다 */
const VITK_YES = ['청국장찌개', '낫토', '시금치나물', '케일주스', '브로콜리 데침']
const VITK_NO = ['시금치 국수', '케일 쿠키', '브로콜리 크래커', '상추', '깻잎']
for (const n of VITK_YES) no(!has(n, '고비타민K'), `"${n}" 에 고비타민K 가 안 붙는다 — 와파린 경고를 놓친다`)
for (const n of VITK_NO) no(has(n, '고비타민K'), `"${n}" 에 고비타민K 가 붙었다 — 규칙이 이름을 든 다섯 가지가 아니거나 색만 낸 것이다`)

/* ── 자료 전체에서 실제로 작동하는가 ─────────────────── */

const ALL: Food[] = [...CURATED_FOODS, ...GENERATED_CORE]
const patient = {
  cancer: 'breast', phase: 'neutropenia', weightKg: 60, heightCm: 163,
  age: 55, sex: 'F', weightLossPct: 0, conditions: [], medications: [],
  history: [], cuisines: ['한식'], onboarded: true
} as unknown as PatientContext

/*
 * 이름만 보고 '이건 날것이다' 라고 사람이 읽을 수 있는 것을 따로 훑는다.
 * autoTags 와 다른 잣대여야 의미가 있으므로, 여기서는 좁고 확실한 것만 본다.
 */
const OBVIOUS = /^(회덮밥|물회|육회|모듬회|회무침|회냉면|생선회)|회$|초밥/
/*
 * 이 그물도 넓으면 헛것을 잡는다. 실제로 두 가지가 걸렸다 —
 * '파강회' 는 데친 쪽파로 묶는 것이고, '김류,초밥김,전체,말린것' 은 마른 김이다.
 * 둘 다 날것이 아니므로 앱이 조용한 것이 옳다.
 */
const NOT_RAW = /유부|계란|강회|숙회|김류|초밥김|스시노리|소스|간장|초장|육수|자숙/
const obvious = ALL.filter((f) => OBVIOUS.test(f.name) && !NOT_RAW.test(f.name))

let silent = 0, praised = 0
for (const f of obvious) {
  const v = evaluateFood(f, patient) as { level?: string }
  if (v.level === 'prefer') {
    praised++
    bads.push(`호중구감소증인데 "${f.name}" 을 권장으로 내놓는다`)
  } else if (v.level !== 'avoid' && v.level !== 'caution') {
    silent++
    bads.push(`호중구감소증인데 "${f.name}" 에 아무 말이 없다`)
  }
}

/*
 * ── 보이는 이름에 밑줄이 새지 않는가 ────────────────────
 *
 * 식약처 자료는 '피자_쉬림프 피자 골드' 처럼 분류와 이름을 밑줄로 잇는다.
 * 그대로 내보이면 '회덮밥_모듬' 처럼 고장 난 화면으로 읽힌다.
 * 판정에 쓰는 원본은 그대로 두고 보이는 이름만 다듬으므로, 여기서 새는 것만 본다.
 */
const underscored = GENERATED_CORE.filter((f) => f.name.includes('_'))
no(underscored.length > 0,
   `보이는 이름에 밑줄이 남았다 — ${underscored.length}건 (예: ${underscored.slice(0, 3).map((f) => f.name).join(', ')})`)

/*
 * 다듬다가 이름이 사라지지 않았는가.
 *
 * 처음에는 '두 글자 미만' 을 잣대로 삼았다가 '번·엿·럼·꿀' 을 잡았다 —
 * 넷 다 실제 한 글자 음식 이름이다. 길이는 잣대가 못 된다.
 * 비었는지만 본다.
 */
const emptied = GENERATED_CORE.filter((f) => !f.name.trim())
no(emptied.length > 0, `다듬은 뒤 이름이 빈 것 ${emptied.length}건`)

/*
 * 고기를 '채소·섬유' 이유로 권하지 않는가.
 *
 * 받아 온 자료가 식이섬유 숫자만 보고 '고식이섬유' 를 달아, 치료를 마친 유방암 환자에게
 * 육회가 "권장 — 채소 중심 식사" 로 나오고 있었다(2026-10-13, 식약처 질의서의 예시를
 * 앱과 대조하다 발견). 태그가 아니라 결과를 본다 — 군이 고기인데 섬유 태그가 남아 있으면 걸린다.
 */
const meatFiber = GENERATED_CORE.filter(
  (f) => (f.group === '육류' || f.group === '가금류·난류') && (f.tags ?? []).includes('고식이섬유' as never)
)
no(meatFiber.length > 0,
   `고기 군에 '고식이섬유' 가 붙은 것 ${meatFiber.length}종 — 채소 권장 규칙이 고기에 걸린다: ${meatFiber.slice(0, 4).map((f) => f.name).join(', ')}`)
no(GENERATED_CORE.filter((f) => f.group === '육류').length < 100, '육류 군이 100종도 안 됨 — 이 검사가 헛돌고 있다')

/* 검사가 헛돌지 않는지 — 훑은 것이 0 이면 아무것도 확인하지 않은 것이다 */
const tagged = { raw: 0, cured: 0, grape: 0 }
for (const f of GENERATED_CORE) {
  const t = f.tags ?? []
  if (t.includes('생식동물성' as never)) tagged.raw++
  if (t.includes('가공육' as never)) tagged.cured++
  if (t.includes('자몽계' as never)) tagged.grape++
}
no(tagged.raw === 0, '생식동물성이 하나도 안 붙었다 — 자동 태그가 끊겼다')
no(tagged.cured === 0, '가공육이 하나도 안 붙었다')
no(tagged.grape === 0, '자몽계가 하나도 안 붙었다')
no(obvious.length < 20, `훑은 날것이 ${obvious.length}건뿐 — 검사가 헛돌고 있다`)

console.log(
  bads.length
    ? `자동 태그 검사 — 문제 ${bads.length}종\n` + bads.map((b) => '■ ' + b).join('\n')
    : `자동 태그 검사 완료 — 날것 ${obvious.length}건이 모두 경고됨 · ` +
      `번들에 붙은 태그 (생식동물성 ${tagged.raw} · 가공육 ${tagged.cured} · 자몽계 ${tagged.grape}), 문제 없음`
)
if (bads.length) process.exitCode = 1

import type { CancerId, CancerSubtype, PatientCondition, TreatmentHistory } from './types'

/**
 * 암 환자 운동 처방.
 *
 * 기준선은 ACSM 국제 원탁회의(2019)와 ASCO 2022 권고다.
 *   유산소 — 중강도 주 150분 (또는 고강도 주 75분)
 *   저항  — 주 2회 이상, 주요 근육군
 * 여기에 암종별로 달라지는 부분과, 안전상 반드시 멈춰야 하는 상황을 덧붙였다.
 *
 * "무리하지 마세요" 같은 말은 처방이 아니다. 횟수·강도·판단 기준을 숫자로 적는다.
 */

export interface ExerciseItem {
  /** 무엇을 */
  name: string
  /** 어떻게 — 빈도·시간·강도를 숫자로 */
  dose: string
  /** 왜 이 환자에게 */
  why: string
  kind: '유산소' | '저항' | '유연성·균형' | '재활'
  evidence: 'A' | 'B' | 'C' | 'G'
  refIds: string[]
  /**
   * 이 세부 사항에 해당하는 분에게만 보인다. 비우면 모두에게 보인다.
   *
   * 골밀도 이야기는 아로마타제 억제제를 쓰는 분의 것이다.
   * 삼중음성이라 그 약을 쓰실 일이 없는 분께 "골밀도가 빠르게 떨어집니다" 라고
   * 말하는 것은 도움이 아니라 겁주기다.
   */
  subtypes?: CancerSubtype[]
}

export interface ExercisePlan {
  /** 이 암종에서 운동이 갖는 의미 한 문단 */
  summary: string
  items: ExerciseItem[]
  /** 이 암종에서 특히 조심할 것 */
  cautions: string[]
}


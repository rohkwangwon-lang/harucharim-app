export type FoodForm =
  | 'ingredient'  // 식재료 (생 또는 기본 조리)
  | 'dish'        // 조리된 한 그릇 음식
  | 'processed'   // 포장 가공식품
  | 'beverage'
  | 'snack'
  | 'eatout'      // 외식 메뉴

export interface Food {
  id: string
  /** 대표 표기명 */
  name: string
  /** 검색용 동의어·이명 (예: '고구마' ← '군고구마', 'sweet potato') */
  aliases?: string[]
  group: FoodGroup
  form: FoodForm
  /** 1회 제공량 — 실제 한국인이 한 번에 먹는 현실적인 양 */
  serving: {
    /** 가식부 그램 */ g: number
    /** 사용자에게 보여줄 표기 (예: '공기 1그릇') */ label: string
  }
  /** 가식부 100 g 당 영양성분 */
  per100: Nutrients
  tags: FoodTag[]
  /** 혈당지수 (포도당 기준, 확인된 값만) */
  gi?: number
  /** 표시용 보충 설명 */
  note?: string
  /** 성분값 출처 — 'kfda' = 식품의약품안전처 식품영양성분DB, 'rda' = 농촌진흥청 표준성분표 */
  src?: 'kfda' | 'rda' | 'usda' | 'label' | 'calc'
  /** 제철. 생략하면 연중으로 본다 */
  season?: Season[]
  /** 요리 계통. 생략하면 한식으로 본다 */
  cuisine?: Cuisine
  /** 유통 바코드(GTIN-13). 포장 제품에만 있다 */
  barcode?: string
  /**
   * 공공데이터에서 자동으로 들여온 항목인지.
   * 성분값은 식약처 자료라 신뢰할 수 있지만, 임상 태그는 성분으로 판정 가능한 것만
   * 붙어 있어 수작업 검토를 거친 항목보다 정보가 얕다. 화면에서 이를 구분해 표시한다.
   */
  auto?: boolean
  /** 제조사 (가공식품) */
  maker?: string
  /** 품목보고번호 — 바코드 조회와 이어붙이는 열쇠 */
  reportNo?: string
}


export interface PatientContext {
  /** 부르는 이름. 로그인하면 자동으로 채워지고, 직접 고칠 수도 있다. */
  name?: string
  cancer: CancerId
  /**
   * 암종 안의 세부 변수 (유방암 호르몬 수용체 등).
   * 비어 있으면 '아직 모름' 으로 보고 세부 규칙을 모두 보여 준다.
   */
  subtypes?: CancerSubtype[]
  phase: Phase
  /** 현재 체중 (kg) */
  weightKg: number
  heightCm: number
  age: number
  sex: 'M' | 'F'
  /** 최근 6개월 체중 감소율 (%) — 악액질 판정 */
  weightLossPct?: number
  /**
   * 기록된 체중에서 읽어 낸 감소율 (%).
   *
   * 위 값은 처음 설정에서 손으로 적으신 것이라 시간이 지나면 실제와 어긋난다.
   * 체중을 적으실 때마다 이 값을 다시 계산해 둔다.
   * 판단할 때는 둘 중 큰 쪽을 쓴다 — 어느 쪽이든 위험을 가리키면 위험한 것이다.
   */
  observedLossPct?: number
  /** 그 감소가 언제부터 얼마 동안인지 — 화면에서 설명할 때 쓴다 */
  observedLossNote?: string
  /** 동반 상태 — 추가 규칙 트리거 */
  conditions: PatientCondition[]
  /** 복용 중인 약제 — 상호작용 검사 */
  medications: string[]
  /**
   * 알레르기 — 식약처 알레르기 유발물질 표시대상 가운데 고르신 것(data/allergens.ts).
   * 고르시면 그 이름이 보이는 음식은 '피하세요' 가 되고 식단에서 빠진다(2026-10-15).
   */
  allergies?: string[]
  /**
   * 신기능저하일 때 투석 여부(2026-10-15). 투석 중이면 단백질이 오히려 더 필요하고(투석으로 빠져나간다),
   * 투석 전이면 신장내과의 제한이 우선이다 — 같은 '신기능저하' 로 묶어 두면 둘 중 한쪽에는 틀린 목표가 된다.
   */
  dialysis?: Dialysis
  /**
   * 최근 거의 못 드신 기간(2026-10-15 재영양 위험). 재영양증후군은 굶다가 다시 먹기 시작할 때의 문제라,
   * 잘 드시고 계신 분께 열량을 낮춰 잡으면 오히려 해가 된다 — 그래서 여쭙고, 해당될 때만 처음 며칠의 목표를 낮춘다.
   */
  lowIntake?: LowIntake
  /** 위 답을 하신 날 — 처음 며칠의 단계적 목표를 이 날부터 센다 */
  lowIntakeSince?: string
  /** 받은 치료 이력 — 영양제·운동 추천에 반영 */
  history?: TreatmentHistory[]
  /** 식단에 섞어도 되는 요리 계통. 비우면 한식만 */
  cuisines?: Cuisine[]
  /** 온보딩을 마쳤는지 */
  onboarded?: boolean
  /**
   * 바코드 스캔을 쓸지.
   *
   * 공공 바코드 자료는 국내 제품을 다 담지 못한다. 스캔이 자주 빗나가면
   * 오히려 성가시므로 꺼 둘 수 있게 한다. 기본은 켬이다.
   */
  useBarcode?: boolean
}


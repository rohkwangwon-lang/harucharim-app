/* ─────────────────────────────── 풀기 ─────────────────────────────── */
const TOKEN = /^(.+?):([\d.]+)\s*([^\d\s]+)$/

export function parseRecipe(text: string): Ingredient[] {
  return text.split(',').map((t) => t.trim()).filter(Boolean).map((t) => {
    const m = TOKEN.exec(t)
    if (!m) throw new Error(`재료 표기 오류: '${t}'`)
    const name = m[1].trim()
    return { name, qty: Number(m[2]), unit: m[3], cat: categoryOf(name) }
  })
}

const PARSED = new Map<string, Ingredient[]>()

/** 이 음식 n인분의 재료. 재료표가 없으면 음식 그 자체 n개(그 음식의 1회 제공량 단위로) */
export function ingredientsOf(food: Food, servings = 1): Ingredient[] {
  const text = RECIPES[food.id]
  if (!text) {
    return [{ name: food.name, qty: servings, unit: '인분', cat: categoryOfFood(food), self: true, label: food.serving.label }]
  }
  let base = PARSED.get(food.id)
  if (!base) { base = parseRecipe(text); PARSED.set(food.id, base) }
  return base.map((i) => ({ ...i, qty: Math.round(i.qty * servings * 100) / 100 }))
}

export function hasRecipe(food: Food): boolean { return !!RECIPES[food.id] }

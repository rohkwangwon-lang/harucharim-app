export function categoryOf(name: string): IngredientCategory {
  if (PANTRY.has(name)) return '양념·기본 재료'
  for (const [re, cat] of CAT_RULES) if (re.test(name)) return cat
  return '가공·기타'
}

/** 음식 그 자체를 살 때의 분류 — 음식 자료의 식품군으로 */
function categoryOfFood(f: Food): IngredientCategory {
  switch (f.group) {
    case '곡류·전분': return '곡류·전분'
    case '두류·대두가공': return '두류·두부'
    case '견과·종실': return '가공·기타'
    case '채소': return '채소'
    case '해조·버섯': return '버섯·해조'
    case '과일': return '과일'
    case '육류': return '육류'
    case '가금류·난류': return /달걀|계란|메추리알/.test(f.name) ? '달걀·유제품' : '육류'
    case '어패류': return '어패류'
    case '우유·유제품': return '달걀·유제품'
    default: return '가공·기타'
  }
}


/* ── 가공육 ─────────────────────────────────────────── */
/*
 * '소세지'(철자), 페퍼로니, 하몽·프로슈토·잠봉(생햄)이 빠져 있었다 — 페퍼로니 샌드위치와
 * 소세지빵이 아무 표시 없이 지나갔다. 생햄은 날것이기도 하지만 그 판단은 여기서 하지 않는다.
 */
/*
 * 훈제오리를 2026-10-13 에 넣었다. IARC 는 가공육을 "염장·경화·발효·훈연 등으로 가공한 고기" 로 정의하고
 * 가금류도 포함된다고 적는다. 받아 온 자료의 훈제오리 160여 종에는 아무 태그가 없어 표시 없이 지나갔다.
 * 훈제 닭가슴살까지 넓히지는 않았다 — 정해 주신 범위(살라미·건조 소시지·훈제오리)가 아니다.
 */
const CURED = /햄(?!버거)|소시지|소세지|쏘시지|쏘세지|베이컨|살라미|페퍼로니|프랑크|비엔나(?!커피)|스팸|런천미트|초리조|파스트라미|프로슈토|하몽|잠봉|판체타|육포|핫도그|훈제\s*오리|오리\s*훈제/
/* 과자·향·시즈닝과 식물성 대체품은 가공육이 아니다 — 하몽 크래커, 페퍼로니맛 감자칩, 비건 소세지 */
/* '화이트비엔나 콜드브루'·'아몬드 비엔나 커피' 도 커피다(2026-10-14 전수 대조) */
const CURED_NOT = /햄버거|비엔나커피|비엔나 커피|커피|콜드브루|라떼|햄스터|크래커|비스킷|감자칩|포테토칩|스낵|생강청|시즈닝|비건|식물성|베지|향$/

/* ── 생강 ──────────────────────────────────────────── */
/*
 * 생강은 오심에 권장으로 나가는 항목인데, ACCP 2012 항응고 지침의 표에는
 * 와파린 병용 시 출혈 위험 증가(오즈비 3.20, 95 % CI 2.42~4.24)로 올라 있다.
 * 권장과 주의가 같은 식품에 붙는 자리라 태그로 만들어 둔다.
 * '생강나무·생강과자' 처럼 생강이 주가 아닌 것까지 잡으면 경고가 무뎌진다.
 */
/* '편강' 은 생강을 저며 절인 것이라 이름에 '생강' 이 없다 — 실제 자료에 들어 있어 따로 적는다 */
const GINGER = /생강|편강|진저(?!에일)/
const GINGER_NOT = /생강나무|생강향|생강맛|과자|쿠키|케이크|사탕|캔디|젤리|비누|샴푸/

/* ── 자몽 ──────────────────────────────────────────── */
/*
 * 푸라노쿠마린은 과육과 즙에 있다. 향만 낸 과자까지 막으면
 * 정작 자몽주스 경고를 대수롭지 않게 여기시게 된다.
 */
/*
 * 라임을 빠뜨리고 있었다. Bailey 2013(CMAJ) 원문은 자몽과 함께
 * "세비야 오렌지·라임·포멜로도 같은 상호작용을 일으킨다" 고 명시한다.
 * 라임에이드·모히또·라임주스가 모두 태그 없이 지나가고 있었다.
 * 반대로 '네이블·발렌시아 같은 단맛 오렌지는 푸라노쿠마린이 없어 상호작용하지 않는다' 고
 * 같은 문단에 적혀 있으므로, 일반 오렌지는 잡지 않는다.
 */
const GRAPEFRUIT = /자몽|포멜로|라임|세비야\s*오렌지/
/* '프라임' 은 라임이 아니다 — 프라임스테이크·레드프라임 양파가 걸린다 */
const GRAPEFRUIT_NOT = /자몽향|자몽맛|라임향|라임맛|프라임|케이크|쿠키|빵|크림|사탕|캔디|젤리|아이스크림|샤베트|샤벳|콜라겐|껌|비누|샴푸|향료/

/**
 * 이름을 보고 붙일 수 있는 임상 태그를 돌려준다.
 * 이미 붙어 있는 태그는 건드리지 않는다 — 손으로 붙인 것이 언제나 우선이다.
 */
/**
 * 식약처 자료는 '우럭회덮밥_양념장' 처럼 양념까지 포함한 요리를 이렇게 적는다.
 * 조미료가 아니라 요리이므로, 조미료 걸름망에 걸리기 전에 이 꼬리를 떼어 낸다 —
 * 떼지 않으면 회덮밥인데 '양념' 이라는 글자 때문에 날것이 아닌 것으로 새어 나간다.
 */
const DISH_WITH_SAUCE = /_양념장$/

/*
 * '식물성에스트로겐' 은 보여 드리는 이름표다 — 규칙은 걸리지 않는다(콩 근거는 '대두이소플라본').
 * 손으로 등록한 석류·아마씨에는 붙어 있는데 공공데이터의 '석류_생것'·'아마씨_볶은것' 에는 없어,
 * 같은 과일이 화면마다 다르게 보였다. 이름이 꼭 맞는 것만 잡는다 — 석류차·석류주스·아마씨유는 아니다.
 */
const PHYTO_DISPLAY = /^(석류|아마씨)([ _](생것|볶은것))?$/
/*
 * 칡뿌리 — 이소플라본(푸에라린·다이드제인)이 많아 갱년기용으로 팔린다. 즙과 생뿌리만 잡는다.
 * 칡 전분과 칡냉면은 녹말을 걸러 낸 것이라 대상이 아니다.
 */
const KUDZU = /^칡(즙|뿌리[ _]생것)$/
/*
 * 뜨겁게 익혀 내는 요리. 호중구가 낮을 때 가공육에 붙는 "김이 날 만큼 데워서" 는 이런 요리에는 필요 없다(이미 익힌다).
 * 밥 요리를 통째로 빼면 차게 먹는 햄김밥·훈제오리 월남쌈까지 빠진다 — 그래서 분류가 아니라 이름으로 가른다(2026-10-14).
 * 핫바·도시락은 넣지 않는다 — 데워 드시라는 말이 그대로 맞다.
 */
const HOT_DISH = /볶음|덮밥|찌개|국밥|짜글이|전골|탕$|탕[ _(]|구이|떡볶이|피자|라면|우동|짬뽕|솥밥|그라탕|스튜|카레|부침|커틀릿|돈까스|돈가스|리조또|파스타|스파게티/
const ROYAL_JELLY = /로[열얄]\s?젤리/
/* 차게 먹는 음식 — 옥살리플라틴 상호작용이 쓴다. 냉동식품(만두·피자)은 데워 먹으므로 '냉동' 은 넣지 않는다 */
const COLD = /아이스크림|빙수|셔벗|샤베트|샤벳|젤라또|소프트\s?콘|아이스\s?(커피|티|라떼|아메리카노|초코|바|크림)|아이스바|하드바|슬러시|프라푸치노|냉면|밀면|냉모밀|냉소바|냉국|콩국수|물회|얼음/
const COLD_NOT = /아이스크림\s?(맛|향)|쿠키|케이크|빵|과자|떡$/
export function isCold(name: string): boolean {
  return COLD.test(name) && !COLD_NOT.test(name)
}
/*
 * 끈적하게 뭉치는 것 — 떡·찹쌀(2026-10-15 안전 검토).
 * 연하곤란 규칙(cond-dys-rough)은 이유 글에 "떡처럼 끈적하게 뭉치는 것은 특히 위험" 이라 적어 두고,
 * 정작 공공데이터 떡 760종 가운데 757종에는 '점착성' 이 없어 가래떡·인절미가 아무 표시 없이 지나갔다.
 * 떡갈비는 떡이 아니고, 떡맛 과자·소스는 떡이 들어 있지 않다.
 */
const STICKY = /떡|인절미|경단|약식|약밥|찹쌀|모찌|찰떡|증편|송편|절편|백설기|가래떡|쑥개떡|화전/
const STICKY_NOT = /떡갈비|떡맛|떡볶이\s?소스|떡볶이\s?양념|소스|양념장|분말|가루|시즈닝|향/
export function isSticky(name: string): boolean {
  return STICKY.test(name) && !STICKY_NOT.test(name)
}
/*
 * 날로 먹는 일이 흔한 동물성 '생것'(2026-10-15 안전 검토).
 * 표준성분표는 '굴류,굴,육,생것' 처럼 적어 위의 회·초밥 걸름망을 지나갔고,
 * 호중구가 낮은 분께 연어알·성게·생간이 단백질 규칙으로 '권장' 이 되었다.
 * 고기·생선 '생것' 을 통째로 잡지 않는 까닭 — 쇠고기 등심 생것은 익혀 먹을 재료다. 그것까지 피하라면 단백질을 끊으라는 말이 된다.
 * 여기에는 실제로 날로 먹는 것만 둔다.
 */
const RAW_EATEN = /굴|성게|멍게|우렁쉥이|해삼|개불|연어\s?알|연어,\s?알|날치\s?알|천엽|처녑|간,\s?생것|간\s생것|육회/

export function autoTags(name: string): FoodTag[] {
  const s = name.replace(DISH_WITH_SAUCE, '').replace(BRAND, ' ')
  const out: FoodTag[] = []

  const rawJang = RAW_JANG.test(s) && !RAW_JANG_NOT.test(s)
  const cooked = COOKED.test(s) && !RAW_DESPITE_SMOKE.test(s)
  if (rawJang || (!cooked && !NOT_FOOD.test(s) && !SUSHI_COOKED.test(s) && RAW.test(s))) {
    out.push('생식동물성' as FoodTag)
    if (!LAND_RAW.test(s)) out.push('날해산물' as FoodTag)
  }
  if (UNDERCOOKED.test(s) && !UNDERCOOKED_NOT.test(s)) out.push('덜익힘' as FoodTag)
  if (SALTED.test(s) && !SALTED_NOT.test(s)) out.push('염장' as FoodTag)
  if (VITK.test(s) && !VITK_NOT.test(s)) out.push('고비타민K' as FoodTag)
  if (SPROUT.test(s) && !SPROUT_COOKED.test(s)) out.push('생새싹' as FoodTag)
  if (CURED.test(s) && !CURED_NOT.test(s)) out.push('가공육' as FoodTag)
  if (GRAPEFRUIT.test(s) && !GRAPEFRUIT_NOT.test(s)) out.push('자몽계' as FoodTag)
  if (GINGER.test(s) && !GINGER_NOT.test(s)) out.push('생강' as FoodTag)
  if (PHYTO_DISPLAY.test(name.trim())) out.push('식물성에스트로겐' as FoodTag)
  if (KUDZU.test(name.trim())) out.push('칡뿌리' as FoodTag, '식물성에스트로겐' as FoodTag)
  if (ROYAL_JELLY.test(s)) out.push('로열젤리' as FoodTag)
  if (HOT_DISH.test(s) && !/샐러드|냉/.test(s)) out.push('익힌요리' as FoodTag)  // 스파게티샐러드·냉파스타는 차게 먹는다
  if (isSticky(s)) out.push('점착성' as FoodTag)
  if (isCold(s)) out.push('찬음식' as FoodTag)
  if (/오렴자|카람볼라|스타\s?후르츠|스타\s?프루트/.test(s)) out.push('스타후르츠' as FoodTag)

  return out
}

/**
 * 고기 요리에는 '고식이섬유' 를 붙이지 않는다.
 *
 * 받아 온 자료는 식이섬유가 1회 5 g 을 넘으면 기계적으로 이 태그를 단다. 그런데 이 태그는
 * "채소 중심 식사는 체중과 대사 양쪽에서 도움이 됩니다"(유방암), "식이섬유를 하루 30 g 이상으로
 * 올리세요"(대장암) 같은 **권장** 규칙을 끌어온다. 그래서 치료를 마친 분께 육회가
 * '권장 — 채소 중심 식사' 로 나오고 있었다(원자료는 육회 150 g 에 섬유 9.9 g — 곁들인 배·채소 몫이다).
 * 베이컨칩과 탕수육도 같았다. 숫자가 맞더라도 고기를 채소로 권하는 것은 틀렸다.
 *
 * 어패류는 건드리지 않는다. 그 군에 걸린 넷은 미역튀각·김자반·파래자반으로, 실제로 섬유가 많은 해조다.
 */
const NO_FIBER_PRAISE = new Set<string>(['육류', '가금류·난류'])

/* ── 날로 먹는 과일·채소 ─────────────────────────────────────
 *
 * 막으려는 것이 아니라 "씻어서 드세요" 를 함께 보여 주려는 태그다(types.ts 의 '생채소과일').
 * 받아 온 과일·채소는 이름 끝에 상태가 적혀 있다 — '생것' 456종, '데친것' 118종, '말린것' 66종.
 * 샐러드·겉절이는 군이 제각각이라(가공식품 2,400여 종) 이름으로 본다.
 * 감자·달걀·마카로니 샐러드처럼 익혀 으깬 것, 드레싱·토핑, 샐러드 맛 과자와 빵은 날채소가 아니다.
 */
const PRODUCE_GROUPS = new Set<string>(['과일', '채소'])
const RAW_STATE = /생것|숙과/
const RAW_DISH = /샐러드|겉절이|쌈\s*채소|모[둠듬]\s*쌈|컵\s*과일|과일\s*컵|생과일|조각\s*과일/
const RAW_DISH_NOT = /드레싱|소스|시즈닝|토핑|크루통|과자|칩|스낵|쿠키|빵|번$|샌드|버거|피자|김밥|파스타|김치|샐러드\s*바|밥바|한\s*알|마카로니|감자|고구마|단호박|에그|계란|달걀|참치|맛살|크래미|음료|주스|쥬스|젤리|맛$|향$|가루|분말|건조|말린|동결|유$|오일|마요|스프레드|통조림|병조림|볶음|구이|튀김/
const NOT_PRODUCE_GROUPS = new Set<string>(['유지·당류', '음료', '간식·디저트', '우유·유제품', '외식·프랜차이즈'])

function rawProduce(name: string, group?: string): boolean {
  if (!group || NOT_PRODUCE_GROUPS.has(group)) return false
  if (PRODUCE_GROUPS.has(group) && RAW_STATE.test(name)) return true
  return RAW_DISH.test(name) && !RAW_DISH_NOT.test(name)
}


import type { FoodTag } from '../types'

/**
 * 받아 온 식품에 임상 태그를 붙인다.
 *
 * 규칙은 태그로 걸린다. 그런데 손으로 등록한 542종에만 태그가 붙어 있고,
 * 식약처에서 받아 온 것에는 성분값으로 셀 수 있는 태그(고나트륨 같은 것)만 붙었다.
 * 그래서 '회덮밥' 이 호중구감소증 환자에게 아무 말 없이 지나갔고,
 * '모듬회' 는 분류가 육류로 되어 있어 단백질 규칙에 걸려 **권장**으로 나왔다.
 *
 * 만든 쪽은 일부러 좁게 잡았다 — "잘못 붙으면 위험한 태그는 분류가 명확할 때만".
 * 조심한 방향이 반대였다. 안전 태그는 **빠뜨리는 쪽이 더 위험하다.**
 * 잘못 붙으면 안 드셔도 될 것을 피하시게 되지만, 빠뜨리면 드시면 안 될 것을 드시게 된다.
 *
 * 다만 아무렇게나 넓히지는 않는다. 명백히 익힌 것(자숙·데친·구이)과
 * 조미료(초장·간장·소스)까지 '날것' 이라 하면, 정작 진짜 경고를 믿지 않게 된다.
 * 그래서 이름을 세 겹으로 본다 — 상호를 걷어내고, 익힌 것과 조미료를 빼고, 그 다음 판정한다.
 *
 * 패턴은 상상으로 짜지 않고 실제 이름 290,836건을 훑어서 만들었다.
 * '로투스시나몬쿠키'(스시), '저분자몽모랑시'(자몽), '2회분'(회) 같은 것이
 * 그 과정에서 걸러졌다. 검사(scripts/checks/autotag.ts)가 양쪽을 다 지킨다.
 */

/* ── 이름에서 먼저 걷어낼 것 — 음식과 상관없는 낱말 ───────── */
const BRAND = /상회|회관|회오리|회사|회원|회의|회식|회복|\d+\s*회분?|회차|하회마을|만월회|시나몬|시크릿|저분자/g

/* ── 날것 ──────────────────────────────────────────── */

/** 익힌 것 — 자숙(삶음)·숙회(데침)는 날것이 아니다 */
const COOKED = /자숙|숙회|데친|삶은|구이|그릴|튀김|볶음|찜|조림|초절임|훈제|불초밥|굴전/
/** 조미료·가공품 — 회초장·사시미간장·초밥김은 음식이 아니라 곁들이는 것 */
const NOT_FOOD = /초장|소스|육수|양념|드레싱|시즈닝|분말|가루|다시|간장|식초|쇼유|타마리|마요|스프|젤리|쿠키|과자|빵|케이크|쉐이크|칩|초밥김|스시노리|김류/
/** 이름은 초밥이지만 날생선이 아닌 것 */
const SUSHI_COOKED = /유부\s*초밥|유부\s*스시|계란\s*초밥|김\s*초밥/

/** 날로 먹는 생선 — '회' 앞에 붙는 것들 */
const RAW_FISH = '광어|우럭|숭어|참돔|도미|방어|연어|참치|한치|아나고|붕장어|장어|홍어|가오리|간재미|서대|명태|고등어|전어|농어|감성돔|병어|가자미|삼치|송어|전복'
/**
 * 무침으로 날로 먹는 것만 추린다.
 * 오징어·낙지·문어 무침은 데쳐서 만드는 것이라 여기 넣지 않는다 —
 * 넣으면 '오징어무침' 이 날것으로 잡힌다.
 */
const RAW_MUCHIM = /(홍어|간재미|가오리|명태|서대)\s*(회)?무침/

const RAW = new RegExp(
  `(${RAW_FISH})\\s*회` + '|' + RAW_MUCHIM.source +
  '|^회$|^회\\(|모듬회|모둠회|물회|육회|생선회|회덮밥|회무침|회국수|회비빔밥|회냉면|회쌈' +
  '|사시미|카르파초|세비체' +
  /*
   * 초밥은 재료가 익은 것이어도 잡는다.
   * 문어·장어 초밥은 익혀서 올리지만, 호중구가 낮은 동안에는
   * 초밥 자체를 피하라는 것이 FDA 식품안전 권고이고 임상에서 쓰는 기준이다.
   */
  '|초밥|^스시|스시$' +
  '|생굴|굴회|산낙지|낙지탕탕이|생연어'
)

/* ── 생 새싹채소 ──────────────────────────────────
 *
 * '생채소는 씻어 드시면 된다' 의 예외다. FDA 는 'Raw sprouts (alfalfa, bean, or any
 * other sprout)' 를 위험 높은 쪽에, 'Cooked sprouts' 를 낮은 쪽에 짝지어 둔다 —
 * 싹을 틔우는 따뜻하고 습한 환경 자체가 균에 유리해서 씻는 것으로 해결되지 않는다.
 * 데친·볶은·무친 것은 익힌 것이므로 뺀다.
 */
const SPROUT = /숙주|콩나물|새싹|무순|알팔파|스프라우트/
const SPROUT_COOKED = /데친|삶은|볶음|무침|국|탕|찌개|찜|전|밥|죽|구이|조림|튀김/

/* ── 가공육 ────────────────────────────────────────── */
/* 햄버거의 패티는 가공육이 아니고, 비엔나커피는 고기가 아니다 */
/* ── 장에 담근 날것 ─────────────────────────────────── */
/*
 * 간장게장·양념게장·새우장·연어장은 익히지 않은 해산물이다. 그런데 한동안 '주의' 에 그쳤다.
 * 위의 조미료 걸름망(NOT_FOOD)에 '간장' 과 '양념' 이 들어 있어서다 — 사시미간장·회초장을
 * 걸러 내려던 것이 **간장**게장·**양념**게장까지 걸러 냈다. 호중구가 낮은 분께 간장게장 170종,
 * 양념게장 126종, 새우장 156종, 연어장 25종이 '피하세요' 없이 지나갔다(2026-10, 이름으로 세운
 * 상식 검사가 찾음). 그래서 이것들은 조미료 걸름망을 거치지 않는 따로 난 길로 본다.
 *
 * 걸러 낼 것은 실제 이름을 훑어 정했다 — 게장소스·게장용 간장·게장다대기(담그는 양념),
 * 새우장 담는 간장, 간장새우칩·간장새우맛(과자), 간장새우볶음밥(익힘), 생굴전(익힘), 가열한 것.
 * 전복장은 넣지 않았다. 쪄서 담그는 것이 보통이라 날것이라 단정할 수 없다.
 */
const RAW_JANG = /게장|새우장|간장\s*새우|연어장|생굴/
/* '가열하지 않고 섭취하는' 은 날것이라는 뜻이다 — '가열' 만 보고 빼면 거꾸로 된다 */
const RAW_JANG_NOT = /소스|다대기|담는|시즈닝|분말|가루|칩|과자|스낵|가열(?!하지)|볶음밥|덮죽|생굴전|게장\s*용?\s*(양념|간장)|간장\s*새우\s*맛/

/* ── 젓갈 ──────────────────────────────────────────── */
/*
 * '염장' 은 원자료의 분류가 '젓갈류' 일 때만 붙었다. 그런데 "새우, 젓갈, 추젓" 처럼
 * 다른 분류에 든 젓갈이 수백 종 있다. 그것들은 태그가 없어 위암의 염장식품 '피하세요' 를
 * 빠져나갔고, 단백질이 많다는 이유로 오히려 **권장**으로 떴다(새우젓 31종).
 *
 * 젓으로 간을 한 요리(달걀찜 새우젓, 무생채 액젓)와 젓갈 김밥·쌈장·소스는 넣지 않는다 —
 * 그것은 염장식품이 아니라 그것을 넣은 음식이다. "젓갈 없는 김치" 도 실제로 있었다.
 */
/*
 * 장아찌·단무지·짠지와 소금에 절인 생선(굴비·간고등어·자반고등어)도 같다.
 * 위암 규칙의 제목이 "젓갈·자반·장아찌 같은 염장식품" 인데, 장아찌 465종 중 15종,
 * 단무지 302종 중 2종, 굴비·간고등어 110종 중 0종에만 태그가 있었다.
 * '자반' 은 그대로 쓰지 못한다 — 김자반·콩자반·모자반은 절인 생선이 아니다.
 * '굴비' 도 조심한다 — "매생이굴 비빔밥" 이 걸린다(아래 걸름망의 '비빔밥' 이 막는다).
 */
const SALTED = new RegExp(
  '젓갈|액젓|[가-힣]젓(?![가-힣])' +
  '|(명란|창란|창난|오징어|낙지|꼴뚜기|새우|조개|어리굴|멸치|까나리|갈치속|토하|밴댕이|황석어|아가미|가리비|씨앗)젓' +
  '|장아찌|짠지|단무지' +
  '|자반\\s*고등어|고등어\\s*자반|간고등어|굴비'
)
/* '김밥' 은 젓갈김밥을 빼려던 것인데 김밥단무지까지 뺐다 — 단무지가 뒤따르면 그대로 둔다 */
const SALTED_NOT = /없는|김밥(?!\s*용?\s*단무지)|삼각|쌈장|마요|소스|김치|삼겹|고추장?\s*불고기|불고기|페이스트|무말랭|찜|찌개|젓국|전$|볶음|파스타|덮밥|비빔밥|주먹밥|바게트|빵|과자|스낵|칩|생채|젓[가-힣]*\s*무침|장아찌\s*(용\s*)?간장|양념장|짜글이/

/* ── 비타민 K ──────────────────────────────────────── */
/*
 * 와파린 규칙은 이유 글에서 "시금치·케일·브로콜리·청국장·낫토는 비타민 K 가 많습니다" 라고
 * 이름을 든다. 그런데 '고비타민K' 는 비타민 K 수치가 있어야 붙고, 받아 온 자료 대부분에는
 * 그 수치가 없다. 그래서 청국장 13종 중 1종, 케일 14종 중 2종에만 와파린 경고가 떴고,
 * 와파린을 드시는 분의 추천 식단에 청국장이 올라왔다(2026-10).
 *
 * 규칙이 이름을 든 다섯 가지만 넣는다. 더 넓히는 것은 근거를 보고 정할 일이다.
 * 색만 낸 과자·국수·빵은 뺀다.
 */
const VITK = /시금치|케일|브로콜리|청국장|낫토/
const VITK_NOT = /과자|쿠키|칩|스낵|캔디|사탕|젤리|빵|케이크|크래커|향|국수|파스타|소스|시즈닝|케일라스|스케일/

/* ── 가공육 ─────────────────────────────────────────── */
/*
 * '소세지'(철자), 페퍼로니, 하몽·프로슈토·잠봉(생햄)이 빠져 있었다 — 페퍼로니 샌드위치와
 * 소세지빵이 아무 표시 없이 지나갔다. 생햄은 날것이기도 하지만 그 판단은 여기서 하지 않는다.
 */
const CURED = /햄(?!버거)|소시지|소세지|쏘시지|쏘세지|베이컨|살라미|페퍼로니|프랑크|비엔나(?!커피)|스팸|런천미트|초리조|파스트라미|프로슈토|하몽|잠봉|판체타|육포|핫도그/
/* 과자·향·시즈닝과 식물성 대체품은 가공육이 아니다 — 하몽 크래커, 페퍼로니맛 감자칩, 비건 소세지 */
const CURED_NOT = /햄버거|비엔나커피|햄스터|크래커|비스킷|감자칩|포테토칩|스낵|생강청|시즈닝|비건|식물성|베지|향$/

/* ── 생강 ──────────────────────────────────────────── */
/*
 * 생강은 오심에 권장으로 나가는 항목인데, ACCP 2012 항응고 지침의 표에는
 * 와파린 병용 시 출혈 위험 증가(오즈비 3.20, 95 % CI 2.42~4.24)로 올라 있다.
 * 권장과 주의가 같은 식품에 붙는 자리라 태그로 만들어 둔다.
 * '생강나무·생강과자' 처럼 생강이 주가 아닌 것까지 잡으면 경고가 무뎌진다.
 */
/* '편강' 은 생강을 저며 절인 것이라 이름에 '생강' 이 없다 — 실제 자료에 들어 있어 따로 적는다 */
const GINGER = /생강|편강|진저(?!에일)/
const GINGER_NOT = /생강나무|생강향|생강맛|과자|쿠키|케이크|사탕|캔디|젤리|비누|샴푸/

/* ── 자몽 ──────────────────────────────────────────── */
/*
 * 푸라노쿠마린은 과육과 즙에 있다. 향만 낸 과자까지 막으면
 * 정작 자몽주스 경고를 대수롭지 않게 여기시게 된다.
 */
/*
 * 라임을 빠뜨리고 있었다. Bailey 2013(CMAJ) 원문은 자몽과 함께
 * "세비야 오렌지·라임·포멜로도 같은 상호작용을 일으킨다" 고 명시한다.
 * 라임에이드·모히또·라임주스가 모두 태그 없이 지나가고 있었다.
 * 반대로 '네이블·발렌시아 같은 단맛 오렌지는 푸라노쿠마린이 없어 상호작용하지 않는다' 고
 * 같은 문단에 적혀 있으므로, 일반 오렌지는 잡지 않는다.
 */
const GRAPEFRUIT = /자몽|포멜로|라임|세비야\s*오렌지/
/* '프라임' 은 라임이 아니다 — 프라임스테이크·레드프라임 양파가 걸린다 */
const GRAPEFRUIT_NOT = /자몽향|자몽맛|라임향|라임맛|프라임|케이크|쿠키|빵|크림|사탕|캔디|젤리|아이스크림|샤베트|샤벳|콜라겐|껌|비누|샴푸|향료/

/**
 * 이름을 보고 붙일 수 있는 임상 태그를 돌려준다.
 * 이미 붙어 있는 태그는 건드리지 않는다 — 손으로 붙인 것이 언제나 우선이다.
 */
/**
 * 식약처 자료는 '우럭회덮밥_양념장' 처럼 양념까지 포함한 요리를 이렇게 적는다.
 * 조미료가 아니라 요리이므로, 조미료 걸름망에 걸리기 전에 이 꼬리를 떼어 낸다 —
 * 떼지 않으면 회덮밥인데 '양념' 이라는 글자 때문에 날것이 아닌 것으로 새어 나간다.
 */
const DISH_WITH_SAUCE = /_양념장$/

export function autoTags(name: string): FoodTag[] {
  const s = name.replace(DISH_WITH_SAUCE, '').replace(BRAND, ' ')
  const out: FoodTag[] = []

  const rawJang = RAW_JANG.test(s) && !RAW_JANG_NOT.test(s)
  if (rawJang || (!COOKED.test(s) && !NOT_FOOD.test(s) && !SUSHI_COOKED.test(s) && RAW.test(s))) {
    out.push('생식동물성' as FoodTag)
  }
  if (SALTED.test(s) && !SALTED_NOT.test(s)) out.push('염장' as FoodTag)
  if (VITK.test(s) && !VITK_NOT.test(s)) out.push('고비타민K' as FoodTag)
  if (SPROUT.test(s) && !SPROUT_COOKED.test(s)) out.push('생새싹' as FoodTag)
  if (CURED.test(s) && !CURED_NOT.test(s)) out.push('가공육' as FoodTag)
  if (GRAPEFRUIT.test(s) && !GRAPEFRUIT_NOT.test(s)) out.push('자몽계' as FoodTag)
  if (GINGER.test(s) && !GINGER_NOT.test(s)) out.push('생강' as FoodTag)

  return out
}

/**
 * 고기 요리에는 '고식이섬유' 를 붙이지 않는다.
 *
 * 받아 온 자료는 식이섬유가 1회 5 g 을 넘으면 기계적으로 이 태그를 단다. 그런데 이 태그는
 * "채소 중심 식사는 체중과 대사 양쪽에서 도움이 됩니다"(유방암), "식이섬유를 하루 30 g 이상으로
 * 올리세요"(대장암) 같은 **권장** 규칙을 끌어온다. 그래서 치료를 마친 분께 육회가
 * '권장 — 채소 중심 식사' 로 나오고 있었다(원자료는 육회 150 g 에 섬유 9.9 g — 곁들인 배·채소 몫이다).
 * 베이컨칩과 탕수육도 같았다. 숫자가 맞더라도 고기를 채소로 권하는 것은 틀렸다.
 *
 * 어패류는 건드리지 않는다. 그 군에 걸린 넷은 미역튀각·김자반·파래자반으로, 실제로 섬유가 많은 해조다.
 */
const NO_FIBER_PRAISE = new Set<string>(['육류', '가금류·난류'])

/** 이미 있는 태그에 자동 태그를 합친다. 군을 주면 그 군에 맞지 않는 태그를 덜어 낸다 */
export function withAutoTags(name: string, tags: FoodTag[], group?: string): FoodTag[] {
  const kept = group && NO_FIBER_PRAISE.has(group)
    ? tags.filter((t) => t !== ('고식이섬유' as FoodTag))
    : tags
  const extra = autoTags(name).filter((t) => !kept.includes(t))
  return extra.length ? [...kept, ...extra] : kept
}

/**
 * 화면에 보일 이름.
 *
 * 식약처 자료는 '피자_쉬림프 피자 골드 (L)' 처럼 분류와 이름을 밑줄로 잇는다.
 * 17,756건 중 14,427건이 그렇다. 그대로 내보이면 자료가 새는 것처럼 보이고,
 * 실제로 '회덮밥_모듬' 은 고장 난 화면으로 읽힌다.
 *
 * 앞머리가 뒤에 이미 들어 있으면 덜어 낸다 — '피자_… 피자 골드' 는 '피자' 를 두 번 말한다.
 * 그렇지 않으면 띄어쓰기로 잇는다 — '브로콜리_잎_생것' 은 셋 다 뜻이 있다.
 *
 * 판정에 쓰는 이름(food.name 을 만들기 전의 원본)은 건드리지 않는다.
 * 태그 패턴은 원본 이름으로 검증했으므로, 보이는 이름만 다듬는다.
 */
export function displayName(raw: string): string {
  if (!raw.includes('_')) return raw
  const parts = raw.split('_').map((x) => x.trim()).filter(Boolean)
  if (parts.length < 2) return parts.join(' ') || raw

  const [head, ...rest] = parts
  const redundant = rest.some((r) => r.includes(head))
  return (redundant ? rest : parts).join(' ')
}
